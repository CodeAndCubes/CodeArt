package com.mrleonardos.codeart.client;

/**
 * Текстура арта, общая для статичной картинки и атласа кадров.
 *
 * <p>
 * Заливается по частям из главного потока клиента: большой арта в одну команду заливки отнимает заметную
 * часть кадра, и пока заливка не закончена, рисуется заглушка с прогрессом. Рендерер спрашивает кадр и
 * координаты текстуры через этот интерфейс и не знает, статика под ним или анимация.
 */
public interface ArtTexture {

    /** Залить очередную порцию. Звать из главного потока клиента, пока {@link #isReady()} не станет истинным. */
    void uploadStep();

    /** Закончилась ли заливка. */
    boolean isReady();

    /** Какая доля пикселей уже уехала в видеокарту. */
    float uploadProgress();

    /** Привязать текстуру. */
    void bind();

    /** Выгрузить текстуру и отпустить память. */
    void dispose();

    /** Есть ли в текстуре больше одного кадра. */
    boolean isAnimated();

    /** Кадр, который пора показывать на этот момент времени. */
    int frameAt(long elapsedMillis);

    float minU(int frame);

    float maxU(int frame);

    float minV(int frame);

    float maxV(int frame);

    /** Сколько памяти держит текстура, в байтах: считается от сторон без обращения к состоянию GL. */
    long memoryFootprint();

    long lastUsedMillis();

    void markUsed(long now);
}
