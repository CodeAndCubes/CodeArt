package com.mrleonardos.codeart.api;

import java.util.List;

/**
 * Шов хранилища артов: где лежит реестр и байты картинок.
 *
 * <p>
 * Встроенная реализация держит {@code arts.json} и файлы по хешу в папке настроек. Свою приносит мод,
 * который зарегистрировал её в {@link ArtApi} на своей инициализации: активным становится провайдер, чьё
 * имя стоит в {@code [storage] provider} главного файла линейки.
 *
 * <p>
 * Методы с колбэком отвечают не раньше следующего тика: разрешение источника это чтение файла или ход в
 * сеть, и главный поток на это не ставится. Колбэк получает ключ перевода и аргументы, а не готовую
 * строку: сервер собирает текст по языку из главного файла, и рабочий поток языка не знает.
 */
public interface ArtStore {

    /** Имя провайдера, по которому его выбирает секция {@code [storage]} главного файла. */
    String id();

    /** Прочитать реестр и разрешить источники. Зовётся на старте сервера. */
    void start();

    /** Перечитать реестр с диска и переслать манифест подключённым. */
    void reload(Callback callback);

    /** Разрешить новый источник и добавить арт в реестр. */
    void add(ArtRecord record, Callback callback);

    /** Снять арт с реестра и удалить его из манифеста. */
    void remove(String name, Callback callback);

    /** Все записи реестра: готовые арты и ошибки разрешения рядом. */
    List<ArtEntry> entries();

    /** Запись по имени или {@code null}. */
    ArtEntry entry(String name);

    /** Определение готового арта по имени или {@code null}. */
    ArtDefinition definition(String name);

    /** Опубликован ли этот хеш: по нему клиенты просят байты. */
    boolean isPublished(String sha256);

    /** Байты картинки по хешу или {@code null}, если файла нет или он не сходится с хешем. */
    byte[] content(String sha256);

    /** Выполнить задачу в рабочем потоке хранилища: чтение и скачивание не стоят в тике. */
    void execute(Runnable task);

    /** Остановить рабочие потоки и отпустить состояние. Зовётся при остановке сервера. */
    void stop();

    /** Ответ асинхронной операции: исход и строка для игрока ключом перевода. */
    interface Callback {

        /** Сообщить исход: готовый текст собирает тот, кто показывает строку. */
        void done(boolean success, String messageKey, Object... arguments);
    }
}
